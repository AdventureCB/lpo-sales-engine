alter table crm_contacts add column tz_offset smallint;

create or replace function contact_tz_offset(p_phones jsonb) returns smallint
language sql stable as $$
  with d as (
    select regexp_replace(coalesce(p_phones->0->>'e164', p_phones->0->>'value', ''), '\D', '', 'g') as num
  )
  select a.utc_offset
  from d
  join area_code_tz a
    on a.code = case
      when length(d.num) = 11 and left(d.num, 1) = '1' then substr(d.num, 2, 3)
      when length(d.num) >= 10 then left(d.num, 3)
      else null
    end
  limit 1
$$;

create or replace function set_contact_tz() returns trigger language plpgsql as $$
begin
  new.tz_offset := contact_tz_offset(new.phones);
  return new;
end $$;

create trigger trg_contact_tz
  before insert or update of phones on crm_contacts
  for each row execute function set_contact_tz();

update crm_contacts set tz_offset = contact_tz_offset(phones)
where jsonb_array_length(phones) > 0;
